create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9-]+$'),
  name text not null check (char_length(trim(name)) between 1 and 80),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (owner_id, slug),
  unique (owner_id, name)
);

create table if not exists public.bales (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  bale_number bigint generated by default as identity unique,
  code text generated always as ('PAC-' || lpad(bale_number::text, 4, '0')) stored unique,
  purchase_date date not null default current_date,
  purchase_cost numeric(12, 2) not null check (purchase_cost > 0),
  transport_cost numeric(12, 2) not null default 0 check (transport_cost >= 0),
  other_expenses numeric(12, 2) not null default 0 check (other_expenses >= 0),
  received_pieces integer not null check (received_pieces > 0),
  notes text check (char_length(notes) <= 1000),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.bale_inventory (
  id uuid primary key default gen_random_uuid(),
  bale_id uuid not null references public.bales (id) on delete cascade,
  category_id uuid not null references public.categories (id) on delete restrict,
  received_quantity integer not null check (received_quantity > 0),
  sold_quantity integer not null default 0 check (sold_quantity >= 0),
  damaged_quantity integer not null default 0 check (damaged_quantity >= 0),
  available_quantity integer generated always as (received_quantity - sold_quantity - damaged_quantity) stored,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (bale_id, category_id),
  check (sold_quantity + damaged_quantity <= received_quantity)
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 120),
  phone text check (char_length(phone) <= 30),
  is_priority boolean not null default false,
  notes text check (char_length(notes) <= 1000),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.sales (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  customer_id uuid references public.customers (id) on delete set null,
  payment_method text not null check (payment_method in ('cash', 'transfer', 'card', 'other')),
  sold_at timestamptz not null default timezone('utc', now()),
  total numeric(12, 2) not null default 0 check (total >= 0),
  notes text check (char_length(notes) <= 1000),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales (id) on delete cascade,
  category_id uuid not null references public.categories (id) on delete restrict,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12, 2) not null check (unit_price > 0),
  line_total numeric(12, 2) generated always as (quantity * unit_price) stored,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.sale_item_allocations (
  id uuid primary key default gen_random_uuid(),
  sale_item_id uuid not null references public.sale_items (id) on delete cascade,
  bale_inventory_id uuid not null references public.bale_inventory (id) on delete restrict,
  quantity integer not null check (quantity > 0),
  created_at timestamptz not null default timezone('utc', now()),
  unique (sale_item_id, bale_inventory_id)
);

create table if not exists public.expenses (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  bale_id uuid references public.bales (id) on delete set null,
  concept text not null check (char_length(trim(concept)) between 1 and 160),
  amount numeric(12, 2) not null check (amount > 0),
  expense_date date not null default current_date,
  notes text check (char_length(notes) <= 1000),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.damaged_products (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  bale_inventory_id uuid not null references public.bale_inventory (id) on delete restrict,
  quantity integer not null check (quantity > 0),
  reason text not null check (char_length(trim(reason)) between 1 and 500),
  reported_at timestamptz not null default timezone('utc', now()),
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists bales_owner_purchase_date_idx on public.bales (owner_id, purchase_date desc);
create index if not exists bale_inventory_bale_id_idx on public.bale_inventory (bale_id);
create index if not exists bale_inventory_category_id_idx on public.bale_inventory (category_id);
create index if not exists customers_owner_name_idx on public.customers (owner_id, name);
create index if not exists sales_owner_sold_at_idx on public.sales (owner_id, sold_at desc);
create index if not exists sale_items_sale_id_idx on public.sale_items (sale_id);
create index if not exists sale_items_category_id_idx on public.sale_items (category_id);
create index if not exists expenses_owner_expense_date_idx on public.expenses (owner_id, expense_date desc);
create index if not exists damaged_products_inventory_id_idx on public.damaged_products (bale_inventory_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create or replace function public.create_profile_and_categories()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', new.raw_user_meta_data ->> 'name')
  )
  on conflict (id) do nothing;

  insert into public.categories (owner_id, slug, name)
  values
    (new.id, 'shirts', 'Camisas'),
    (new.id, 'blouses', 'Blusas'),
    (new.id, 'pants', 'Pantalones'),
