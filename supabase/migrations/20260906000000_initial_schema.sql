for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create policy "Users manage their categories" on public.categories
for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy "Users manage their bales" on public.bales
for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy "Users manage their inventory" on public.bale_inventory
for all to authenticated
using (exists (select 1 from public.bales b where b.id = bale_id and b.owner_id = (select auth.uid())))
with check (exists (select 1 from public.bales b where b.id = bale_id and b.owner_id = (select auth.uid())));
