for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy "Users read their sales" on public.sales
for select to authenticated using ((select auth.uid()) = owner_id);
create policy "Users read their sale items" on public.sale_items
for select to authenticated
using (exists (select 1 from public.sales s where s.id = sale_id and s.owner_id = (select auth.uid())));
